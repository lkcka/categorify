"""
Промпт для батч-категоризации LLM-фоллбэком.

Few-shot примеры взяты из РЕАЛЬНЫХ ошибок TF-IDF ML-классификатора,
зафиксированных при оценке на golden-наборе в ходе разработки этого
проекта (см. errors.csv на шаге 5), а не выдуманы абстрактно. Цель
примеров — показать модели два паттерна:
 1. Незнакомый бренд категоризируется по смыслу/структуре имени и MCC,
    а не по точному совпадению словаря (то, что TF-IDF не умеет).
 2. Если сигнала объективно недостаточно — честный ответ "Прочее",
    а не угадывание с фальшивой уверенностью.
"""
from expense_categorizer.categories import CATEGORIES
from expense_categorizer.llm.base import LLMItem

FEW_SHOT_EXAMPLES = [
    ("POKUPKA AROMAMANIYA VORONEZH", "", "Красота и уход",
     "название образовано от 'ароматы' — розничный магазин парфюмерии/косметики"),
    ("OPLATA NORDWIND", "4511", "Путешествия",
     "MCC 4511 = авиакомпании; Nordwind — реальный российский авиаперевозчик"),
    ("TAKSOVICHKOF*27965", "", "Транспорт",
     "суффикс *NNNNN — типичный формат мерчант-дескриптора агрегатора такси"),
    ("POKUPKA SLATA ROSTOV-NA-DONU", "5422", "Продукты",
     "MCC 5422 = продуктовые магазины; 'Слата' — региональная розничная сеть"),
    ("ИП Петров И.А.", "", "Прочее",
     "нет описания услуги — определить категорию невозможно, честно отвечаем 'не знаю'"),
    ("OZON.RU", "", "Прочее",
     "маркетплейс общего назначения без указания товара — категория не определима"),
]

SYSTEM_PREAMBLE = f"""Ты — модуль категоризации транзакций банковской выписки физлица (Россия).
Категории (используй ТОЧНО одно из этих значений, без изменений):
{chr(10).join(f"- {c}" for c in CATEGORIES)}

Правила:
1. Если по описанию и MCC-коду нельзя уверенно определить категорию — ответь
   "Прочее" и укажи низкую confidence. Лучше честно не знать, чем угадывать.
2. confidence — твоя самооценка уверенности от 0.0 до 1.0.
 3. Отвечай ТОЛЬКО валидным JSON-массивом без каких-либо пояснений, формат:
 [{{"id": "<id>", "category": "<категория>", "confidence": <число>}}, ...]

ВАЖНО про формат: верхний уровень ответа должен быть ИМЕННО МАССИВОМ (начинается
с символа "["), а НЕ объектом/словарём. Пример НЕПРАВИЛЬНОГО формата (так делать
нельзя): {{"0": [{{"id": "0", "category": "Продукты", "confidence": 1.0}}]}}.
Правильно: [{{"id": "0", "category": "Продукты", "confidence": 1.0}}, ...].
"""


def _format_examples() -> str:
    lines = ["Примеры (описание | MCC -> категория, обоснование):"]
    for desc, mcc, cat, reason in FEW_SHOT_EXAMPLES:
        lines.append(f'- "{desc}" | MCC={mcc or "нет"} -> {cat}  ({reason})')
    return "\n".join(lines)


def build_batch_prompt(items: list[LLMItem]) -> str:
    lines = [SYSTEM_PREAMBLE, "", _format_examples(), "", "Классифицируй следующие транзакции:"]
    for item in items:
        lines.append(f'id="{item.item_id}" | описание="{item.description}" | MCC={item.mcc or "нет"}')
    lines.append("\nВерни JSON-массив ответов для ВСЕХ перечисленных id, в том же порядке.")
    return "\n".join(lines)